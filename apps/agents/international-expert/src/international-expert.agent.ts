function analyzeIntl(query: string): IntlInfo | null {
  const lower = query.toLowerCase();
  for (const [key, info] of Object.entries(INTL_DB)) {
    if (lower.includes(key) || lower.includes(info.name)) return info;
  }
  const fuzzy: Record<string, string> = {
    'صادرات': 'قرارداد بین‌المللی',
    'واردات': 'قرارداد بین‌المللی',
    'خارجی': 'قرارداد بین‌المللی',
    'ارز': 'تحریم',
    'دلار': 'تحریم',
    'LC': 'قرارداد بین‌المللی',
    'اعتبار اسنادی': 'قرارداد بین‌المللی',
    'حمل': 'قرارداد بین‌المللی',
    'داور': 'داوری',
  };
  for (const [f, real] of Object.entries(fuzzy)) {
    if (lower.includes(f)) return INTL_DB[real];
  }
  return null;
}

async function intlExpertExecutor(task: AgentTask, routed: { skillId: string; score: number } | null): Promise<AgentResult> {
  const query = task.query || '';
  const skillId = routed?.skillId || 'intl:general';
  const info = analyzeIntl(query);

  if (info) {
    const output = `**تحلیل بین‌الملل — ${info.persianName}**

**پرسش:** ${query}

### مستندات قانونی:
${info.articles.map(a => `- ${a}`).join('\n')}

### مراحل انجام کار:
${info.procedure.join('\n')}

### مدارک لازم:
${info.documents.map(d => `- ${d}`).join('\n')}

### ریسک‌ها:
${info.risks.map(r => `- ${r}`).join('\n')}

### نکات وکیل بین‌الملل:
${info.notes.join('\n')}

**تذکر:** این تحلیل جنبهٔ اطلاع‌رسانی دارد؛ معاملات بین‌المللی را پیش از امضا با وکیل متخصص بررسی کنید.
`;

    return {
      ok: true,
      output,
      meta: { routedSkillId: skillId, score: routed?.score ?? 0, grounded: true, intlTopic: info.name },
    };
  }

  return {
    ok: true,
    output: `**کارشناس امور بین‌الملل**

**پرسش:** ${query}

لطفا موضوع بین‌الملل را مشخص کنید:
- **تحریم:** ریسک‌های تحریمی، شرط تحریم و قوهٔ قاهره در قرارداد
- **قرارداد بین‌المللی:** صادرات، واردات، اینکوترمز، LC، حمل
- **داوری:** داوری ICC، LCIA، اجرای رای خارجی، کنوانسیون نیویورک

مثال: «شرط تحریم در قرارداد صادرات» یا «تفاوت FOB و CIF چیست؟» یا «هزینهٔ داوری ICC چگونه محاسبه می‌شود؟»

تجارت بین‌الملل ریسک بالا دارد — حتما با وکیل بین‌الملل مشورت کنید.
`,
    meta: { routedSkillId: skillId, score: routed?.score ?? 0, grounded: false },
  };
}

