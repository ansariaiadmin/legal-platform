function analyzeCrime(query: string): { crime: CrimeInfo; matchedKeyword: string } | null {
  const lowerQuery = query.toLowerCase();

  for (const [keyword, info] of Object.entries(CRIMES_DB)) {
    if (lowerQuery.includes(keyword.toLowerCase()) || lowerQuery.includes(info.name)) {
      return { crime: info, matchedKeyword: keyword };
    }
  }

  // Fuzzy matching for related terms
  const fuzzyMap: Record<string, string> = {
    'دزدی': 'سرقت',
    'کلاه برداری': 'کلاهبرداری',
    'کتک': 'ضرب و جرح',
    'قتل': 'قتل',
    'کشت': 'قتل',
    'امانت': 'خیانت در امانت',
    'سند سازی': 'جعل',
    'تهدید کردن': 'تهدید',
    'توهین': 'افترا',
  };

  for (const [fuzzy, real] of Object.entries(fuzzyMap)) {
    if (lowerQuery.includes(fuzzy)) {
      const crimeInfo = CRIMES_DB[real];
      if (crimeInfo) {
        return { crime: crimeInfo, matchedKeyword: real };
      }
    }
  }

  return null;
}

function getDefenseStrategies(crime: CrimeInfo, query: string): string[] {
  const strategies: string[] = [];

  strategies.push(`### دفاعیات اختصاصی جرم ${crime.persianName}:`);
  crime.defenses.forEach((defense, idx) => {
    strategies.push(`${idx + 1}. **${defense}**: بررسی امکان استناد به ${defense}`);
  });

  strategies.push('\n### دفاعیات عام (قابل اعمال در همه جرایم):');
  strategies.push('۱. **دفاع مشروع** (ماده ۱۵۶ قانون مجازات): اثبات ضرورت دفاع و تناسب');
  strategies.push('۲. **جنون** (ماده ۱۴۹): در صورت ابتلا به جنون حین ارتکاب');
  strategies.push('۳. **صغر سن** (ماده ۱۴۷): زیر ۹ سال قمری برای دختر، ۱۵ سال برای پسر');
  strategies.push('۴. **اکراه** (ماده ۱۵۱): اجبار غیرقابل تحمل به ارتکاب جرم');
  strategies.push('۵. **اضطرار** (ماده ۱۵۲): حفظ جان یا مال در برابر خطر شدید');
  strategies.push('۶. **اشتباه** (ماده ۱۵۵): اشتباه در هویت یا موضوع');
  strategies.push('۷. **توبه** (ماده ۱۱۴): در جرایم حق الله');
  strategies.push('۸. **گذشت شاکی** (ماده ۱۰۰): در جرایم قابل گذشت');

  return strategies;
}

