function analyzeFamily(query: string): FamilyLawInfo | null {
  const lower = query.toLowerCase();
  for (const [key, info] of Object.entries(FAMILY_DB)) {
    if (lower.includes(key) || lower.includes(info.name)) return info;
  }
  const fuzzy: Record<string, string> = {
    'جدایی': 'طلاق',
    'متارکه': 'طلاق',
    'بچه': 'حضانت',
    'فرزند': 'حضانت',
    'مهر': 'مهریه',
    'خرجی': 'نفقه',
    'پول': 'نفقه',
  };
  for (const [f, real] of Object.entries(fuzzy)) {
    if (lower.includes(f)) return FAMILY_DB[real];
  }
  return null;
}

async function familyExpertExecutor(task: AgentTask, routed: { skillId: string; score: number } | null): Promise<AgentResult> {
  const query = task.query || '';
  const skillId = routed?.skillId || 'fam:general';
  const analysis = analyzeFamily(query);

  if (analysis) {
    const output = `👨‍👩‍👧‍👦 **تحلیل امور خانواده — ${analysis.persianName}**

**پرسش:** ${query}
**مهارت:** ${skillId} — امتیاز ${routed?.score?.toFixed(2) ?? 'N/A'}
**موضوع:** ${analysis.persianName}

### مستندات قانونی:
${analysis.articles.map(a => `- ${a}`).join('\n')}

### مراحل دادرسی:
${analysis.procedure.join('\n')}

### مدارک لازم:
${analysis.documents.map(d => `- ${d}`).join('\n')}

### نکات مهم وکیل:
${analysis.notes.map(n => `- ⚠️ ${n}`).join('\n')}

### هزینه دادرسی ۱۴۰۳:
- طلاق توافقی: حدود ۲ تا ۴ میلیون تومان (بدون احتساب حق‌الوکاله)
- مطالبه مهریه تا ۱۱۰ سکه: هزینه نصف + قابل جلب
- نفقه: هزینه دادرسی بر اساس مبلغ خواسته

⚠️ **تذکر:** دعاوی خانواده نیاز به مشاوره حضوری و بررسی دقیق دارد. مصلحت خانواده و فرزندان در اولویت است.
`;

    return {
      ok: true,
      output,
      meta: { routedSkillId: skillId, score: routed?.score ?? 0, grounded: true, familyTopic: analysis.name },
    };
  }

  const output = `👨‍👩‍👧‍👦 **کارشناس امور خانواده**

**پرسش:** ${query}
**مهارت:** ${skillId}

برای تحلیل دقیق‌تر، لطفا موضوع را مشخص کنید:
- **طلاق:** توافقی، یک‌طرفه، عسر و حرج، خلع و مبارات
- **حضانت:** حضانت فرزند، ملاقات، سلب حضانت
- **مهریه:** مطالبه، تقسیط، بذل، اجرای ثبت
- **نفقه:** نفقه زوجه، نفقه فرزند، اجرت‌المثل، نحله

مثال: "طلاق توافقی چطوره؟" یا "مهریه ۱۱۰ سکه رو چطور بگیرم؟"

⚠️ دعاوی خانواده حساس است — مشاوره حضوری با وکیل خانواده توصیه می‌شود.
`;

  return {
    ok: true,
    output,
    meta: { routedSkillId: skillId, score: routed?.score ?? 0, grounded: false },
  };
}

