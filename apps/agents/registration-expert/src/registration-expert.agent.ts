function analyzeRegistration(query: string): RegistrationInfo | null {
  const lower = query.toLowerCase();
  for (const [key, info] of Object.entries(REG_DB)) {
    if (lower.includes(key) || lower.includes(info.name)) return info;
  }
  const fuzzy: Record<string, string> = {
    'ملک': 'سند',
    'زمین': 'سند',
    'آپارتمان': 'سند',
    'خانه': 'سند',
    'مغازه': 'سند',
    'ثبت': 'شرکت',
    'برند': 'شرکت',
    'لوگو': 'شرکت',
    'علامت': 'شرکت',
    'مشاع': 'افراز',
    'تقسیم': 'افراز',
    'ارث': 'افراز',
  };
  for (const [f, real] of Object.entries(fuzzy)) {
    if (lower.includes(f)) return REG_DB[real];
  }
  return null;
}

async function registrationExpertExecutor(task: AgentTask, routed: { skillId: string; score: number } | null): Promise<AgentResult> {
  const query = task.query || '';
  const skillId = routed?.skillId || 'reg:general';
  const info = analyzeRegistration(query);

  if (info) {
    const output = `🏛️ **تحلیل امور ثبتی — ${info.persianName}**

**پرسش:** ${query}
**مهارت:** ${skillId} — امتیاز ${routed?.score?.toFixed(2) ?? 'N/A'}

### مستندات قانونی:
${info.articles.map(a => `- ${a}`).join('\n')}

### مراحل انجام کار:
${info.procedure.join('\n')}

### مدارک لازم:
${info.documents.map(d => `- ${d}`).join('\n')}

### هزینه‌های تقریبی ۱۴۰۳:
${info.costs.map(c => `- ${c}`).join('\n')}

### نکات مهم وکیل ثبتی:
${info.notes.join('\n')}

⚠️ **تذکر:** امور ثبتی نیاز به استعلامات به‌روز دارد — قبل از هر معامله استعلام ثبتی بگیرید.
`;

    return {
      ok: true,
      output,
      meta: { routedSkillId: skillId, score: routed?.score ?? 0, grounded: true, regTopic: info.name },
    };
  }

  return {
    ok: true,
    output: `🏛️ **کارشناس امور ثبتی**

**پرسش:** ${query}
**مهارت:** ${skillId}

لطفا موضوع ثبتی را مشخص کنید:
- **سند و ملک:** انتقال سند، استعلام ثبتی، قانون جدید الزام به ثبت رسمی (۱۴۰۳)
- **شرکت و برند:** ثبت شرکت (مسئولیت محدود / سهامی خاص)، ثبت برند و لوگو
- **افراز و تفکیک:** تقسیم ملک مشاع، تفکیک آپارتمان، فروش مال مشاع

مثال: "انتقال سند آپارتمان چطوره؟" یا "ثبت شرکت با مسئولیت محدود"

⚠️ قانون جدید ۱۴۰۳: قولنامه عادی دیگر اعتبار ندارد — حتما رسمی کنید.
`,
    meta: { routedSkillId: skillId, score: routed?.score ?? 0, grounded: false },
  };
}

